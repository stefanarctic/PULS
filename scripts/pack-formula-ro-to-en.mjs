/**
 * Builds src/data/formulaRoToEn.js from formula-unique-utf8.json + formula-en-lines.txt
 * (one English line per Romanian string, same order).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dir = dirname(fileURLToPath(import.meta.url));
const roPath = join(__dir, "formula-unique-utf8.json");
const enPath = join(__dir, "formula-en-lines.txt");
const outPath = join(__dir, "../src/data/formulaRoToEn.js");

const ro = JSON.parse(readFileSync(roPath, "utf8"));
const enText = readFileSync(enPath, "utf8");
const en = enText.split(/\r?\n/).filter((line, i, arr) => {
  // allow trailing newline: drop only final empty line
  if (line === "" && i === arr.length - 1) return false;
  return true;
});

if (ro.length !== en.length) {
  console.error(`Count mismatch: RO ${ro.length}, EN ${en.length}`);
  process.exit(1);
}

const lines = [
  "/** Auto-generated by scripts/pack-formula-ro-to-en.mjs — RO→EN labels for the formula sheet. */",
  "export const FORMULA_RO_TO_EN = {",
];
for (let i = 0; i < ro.length; i++) {
  lines.push(`  ${JSON.stringify(ro[i])}: ${JSON.stringify(en[i])},`);
}
lines.push("};");
lines.push("");
writeFileSync(outPath, lines.join("\n"), "utf8");
console.log("Wrote", outPath, ro.length, "entries");
